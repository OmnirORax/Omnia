import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { emptyUILayout } from '../src/ui/layout.ts';
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox','--disable-dev-shm-usage'] });
try {
  const page = await browser.newPage({ viewport: { width: 1500, height: 1050 }, reducedMotion: 'reduce' });
  page.setDefaultTimeout(10000);
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const layout = { ...emptyUILayout(), panels: { '@devMode': true }, windows: { theme: { x: 30, y: 90, width: 470, height: 800, collapsed: false, pinned: false } } };
  await page.addInitScript(layout => { if (!sessionStorage.getItem('ui-authoring-seeded')) { localStorage.setItem('omnium.ui.layout.v1', JSON.stringify(layout)); sessionStorage.setItem('ui-authoring-seeded','1'); } }, layout);
  await page.goto(process.env.ATLAS_URL || 'http://127.0.0.1:5181/');
  const state = () => page.evaluate(() => JSON.parse(localStorage.getItem('omnium.ui.layout.v1')));
  const theme = page.getByRole('dialog', { name: 'Master controller', exact: true });
  const editor = page.getByRole('dialog', { name: 'UI edit mode', exact: true });
  await editor.waitFor();
  if (await theme.getByRole("button", { name: "Visuals", exact: true }).getAttribute("aria-expanded") === "false") await theme.getByRole("button", { name: "Visuals", exact: true }).click();
  const sets = theme.getByRole('button', { name: 'Appearance targeting sets', exact: true });
  await sets.waitFor();
  const key = await sets.getAttribute('data-ui-drag');
  assert.ok(key.startsWith('window:section:'));
  await sets.click({button:'right'});
  await page.getByRole('menu', {name:'UI frame settings'}).getByRole('button', {name:'Frame handle appearance',exact:true}).click();
  await page.getByRole('textbox', {name:'Frame name',exact:true}).fill('My targeting sets');
  await page.getByRole('textbox', {name:'Frame name',exact:true}).press('Enter');
  await page.locator('[data-ui-control-owner="window:function-appearance"]').click();
  assert.equal((await state()).labels[key], 'My targeting sets');
  console.log('Section title editable through shared frame customization.');
  const hide = theme.locator('[data-ui-function="ui:hideNames"]');
  await hide.click({button:'right'});
  await page.getByRole('textbox', {name:'Function name',exact:true}).fill('Use symbols');
  await page.getByRole('textbox', {name:'Function name',exact:true}).press('Enter');
  await page.locator('[data-ui-control-owner="window:function-appearance"]').click();
  assert.match(await hide.innerText(), /Use symbols/);
  await editor.getByRole('textbox', {name:'New field name',exact:true}).fill('Budget');
  await editor.getByRole('combobox', {name:'New field type',exact:true}).selectOption('number');
  await editor.getByRole('button', {name:'Create field',exact:true}).click();
  await page.waitForFunction(() => Object.keys(JSON.parse(localStorage.getItem('omnium.ui.layout.v1')).customControls ?? {}).length === 1);
  const customId = Object.keys((await state()).customControls)[0];
  const input = page.locator(`[data-ui-function="${customId}"] input`);
  await input.fill('31');
  assert.equal((await state()).customControls[customId].value,31);
  await page.evaluate(() => window.dispatchEvent(new PointerEvent('pointerdown',{button:3,shiftKey:true,bubbles:true,cancelable:true})));
  await page.waitForFunction(id => JSON.parse(localStorage.getItem('omnium.ui.layout.v1')).customControls[id].value===0, customId);
  await page.evaluate(() => window.dispatchEvent(new PointerEvent('pointerdown',{button:4,shiftKey:true,bubbles:true,cancelable:true})));
  await page.waitForFunction(id => JSON.parse(localStorage.getItem('omnium.ui.layout.v1')).customControls[id].value===31, customId);
  console.log('Custom field creation, live value, UI undo/redo passed.');
  const renamed = theme.getByRole('button',{name:'My targeting sets',exact:true});
  await renamed.evaluate(element => element.scrollIntoView({block:'nearest'}));
  const bounds = await renamed.boundingBox();
  await page.mouse.move(bounds.x+12,bounds.y+bounds.height/2);
  await page.mouse.down();
  await page.mouse.move(590,100,{steps:10});
  await page.mouse.up();
  await page.waitForFunction(key => JSON.parse(localStorage.getItem('omnium.ui.layout.v1')).windows[key.slice(7)]?.inline?.detached, key);
  await page.reload();
  await page.locator(`[data-ui-function="${customId}"] input`).waitFor();
  assert.equal((await state()).customControls[customId].value,31);
  assert.equal((await state()).labels['function:ui:hideNames'],'Use symbols');
  assert.equal((await state()).windows[key.slice(7)].inline.detached,true);
  const reopenedEditor = page.getByRole('dialog', {name:'UI edit mode',exact:true});
  await reopenedEditor.getByRole('combobox',{name:'UI control to place',exact:true}).selectOption('ui:hideNames');
  await reopenedEditor.getByRole('button',{name:'Place existing control',exact:true}).click();
  await page.locator('[data-ui-function="ui:hideNames"] input').check();
  assert.equal((await state()).hideNames,true,'placed control retains its live behavior');
  assert.equal((await state()).items['ui:hideNames'].home,false);
  assert.deepEqual(errors,[]);
  console.log('Whole-section dragging and renamed/custom UI survive reload.');
} finally { await browser.close(); }
