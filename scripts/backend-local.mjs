import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { randomBytes } from 'node:crypto';
import { createClient } from '@supabase/supabase-js';
import { localBackendStatus } from './backend-status.mjs';

const config = localBackendStatus();
const url = config.API_URL;

if (process.argv[2] === 'configure') {
  const target = new URL('../.env.local', import.meta.url);
  if (existsSync(target)) throw new Error('.env.local already exists; preserve it and configure public values manually.');
  const key = config.PUBLISHABLE_KEY ?? config.ANON_KEY;
  if (!key) throw new Error('Local publishable key is unavailable.');
  writeFileSync(target, `# Local public backend configuration, generated by backend:configure.\nVITE_SUPABASE_URL=${url}\nVITE_SUPABASE_PUBLISHABLE_KEY=${key}\n`, { mode: 0o600, flag: 'wx' });
  console.log('Wrote public local configuration to .env.local. Restart the frontend dev server.');
} else if (process.argv[2] === 'user') {
  const email = process.argv[3] ?? 'developer@omnia.local';
  const password = randomBytes(24).toString('base64url');
  const key = config.SERVICE_ROLE_KEY ?? config.SECRET_KEY;
  if (!key) throw new Error('Local administrator key is unavailable.');
  const client = createClient(url, key, { auth: { persistSession: false, autoRefreshToken: false } });
  const result = await client.auth.admin.createUser({ email, password, email_confirm: true });
  if (result.error) throw new Error('Local account could not be created; it may already exist. No existing password was changed.');
  mkdirSync(new URL('../.cache/', import.meta.url), { recursive: true });
  const target = new URL(`../.cache/backend-account-${result.data.user.id}.json`, import.meta.url);
  writeFileSync(target, JSON.stringify({ email, password, userId: result.data.user.id }, null, 2) + '\n', { mode: 0o600, flag: 'wx' });
  console.log(`Created a local-only account. Credentials are in ${fileURLToPath(target)}; do not commit or share this file.`);
} else throw new Error('Use configure or user [email].');
