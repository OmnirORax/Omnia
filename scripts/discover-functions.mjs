import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const source = fileURLToPath(new URL("../src/", import.meta.url));
export const generatedFunctionsPath = resolve(source, "properties/functions.generated.ts");
const walk = directory => readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
  const path = resolve(directory, entry.name);
  return entry.isDirectory() ? walk(path) : path.endsWith(".function.ts") ? [path] : [];
});
export function discoverFunctions() {
  const modules = walk(source).sort();
  const modulePath = path => { const name = relative(dirname(generatedFunctionsPath), path).split("\\").join("/"); return name.startsWith(".") ? name : `./${name}`; };
  const text = "// Generated by scripts/discover-functions.mjs. Do not maintain this list by hand.\nimport { initializeFunctions } from \"./function.ts\";\n" +
    modules.map((path, index) => `import function${index} from ${JSON.stringify(modulePath(path))};`).join("\n") +
    `\nexport const CONFIGURABLE_FUNCTIONS = [${modules.map((_, index) => `function${index}`).join(", ")}] as const;\ninitializeFunctions(CONFIGURABLE_FUNCTIONS);\n`;
  let previous = "";
  try { previous = readFileSync(generatedFunctionsPath, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
  if (text !== previous) writeFileSync(generatedFunctionsPath, text);
  return modules;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`Discovered ${discoverFunctions().length} configurable functions.`);
}
